// Enemy.js
class Enemy extends DynamicObject {
    constructor(opts = {}) {
        super(opts);
        this.target = opts.target; // Player
        this.radius = 160;
        this.closeRadius = 60; // The radius where enemy is able to shoot even if the lantern is off
        this.damage = 5;
        this.fireInterval = 3;
        this.loseTime = 4;

        this.state = "idle"; // idle || attacking. Currently, if it's in attack, it will never go back to idle since it's supposed to hunt.
        this.cooldown = 0;
        this.loseTimer = 0;
        this.flash = 0;
    }

    update(dt) {
        const t = this.target;
        const dx = t.coordinate.x - this.coordinate.x;
        const dy = t.coordinate.y - this.coordinate.y;
        const inCircle = dx * dx + dy * dy <= this.effectiveRadius * this.effectiveRadius; // Generated by Claude

        this.flash = Math.max(0, this.flash - dt);

        if (this.state === "idle") {
            if (inCircle) {
                this.state = "attacking";
                this.cooldown = 0;
            }
            return;
        }

        // Attack the player
        if (inCircle) {
            this.cooldown -= dt;
            if (this.cooldown <= 0) {
                t.health -= this.damage;
                this.cooldown = this.fireInterval;
                this.flash = 0.1;
            }
        }

        // Escape sequence
        if (!inCircle && !t.lanternOn) {
            this.loseTimer += dt;
            if (this.loseTimer >= this.loseTime) this.active = false;
        } else {
            this.loseTimer = 0;
        }
    }

    draw(ctx) {
        const x = Math.round(this.coordinate.x);
        const y = Math.round(this.coordinate.y);

        ctx.fillStyle = "#a33";
        ctx.fillRect(x - this.width / 2, y - this.height / 2, this.width, this.height);

        if (this.flash > 0) {
            ctx.strokeStyle = "yellow";
            ctx.beginPath();
            ctx.moveTo(x, y);
            ctx.lineTo(Math.round(this.target.coordinate.x), Math.round(this.target.coordinate.y));
            ctx.stroke();
        }

        if (DEBUG) {
            ctx.strokeStyle = this.state === "attacking" ? "red" : "orange";
            ctx.beginPath();
            ctx.arc(x, y, this.radius, 0, Math.PI * 2);
            ctx.stroke();
            ctx.beginPath();
            ctx.arc(x, y, this.closeRadius, 0, Math.PI * 2);
            ctx.stroke();
        }
    }

    // Get the effective radius for the enemies shooting, depending on if the lantern is lit or not
    get effectiveRadius() {
        return this.target.lanternOn ? this.radius : this.closeRadius;
    }
}